#!/usr/bin/env python3
"""Paper C, C5: derive the four-copy run script and its batch runner from the C1/C3 scripts, leaving them unchanged.

    make_c5_scripts.py exp/femu_fs.sh exp3/c3_batch.sh femu_fs_c5.sh c5_batch.sh

The only change to femu_fs.sh is a state SD: four copies of /usr written and deleted without TRIM, exactly as SC does
with two. The batch runner calls femu_fs_c5.sh instead of femu_fs.sh."""
import sys

base = open(sys.argv[1], encoding="utf-8", newline="").read().replace("\r\n", "\n")
batch = open(sys.argv[2], encoding="utf-8", newline="").read().replace("\r\n", "\n")


def sub(s, a, b):
    assert s.count(a) == 1, a
    return s.replace(a, b)


fs = sub(base, "    SC) STALE='for i in 1 2; do sudo cp -a /usr /mnt/old$i; done' ;;\n",
         "    SC) STALE='for i in 1 2; do sudo cp -a /usr /mnt/old$i; done' ;;\n"
         "    SD) STALE='for i in 1 2 3 4; do sudo cp -a /usr /mnt/old$i; done' ;;\n")
# the deletion after the stale copies (the S1 branch above keeps its own line)
a = "    G 'sudo rm -rf /mnt/old1 /mnt/old2 /mnt/old3 && sudo sync'\nfi\n"
fs = sub(fs, a, "    G 'sudo rm -rf /mnt/old1 /mnt/old2 /mnt/old3 /mnt/old4 && sudo sync'\nfi\n")
open(sys.argv[3], "w", encoding="utf-8", newline="\n").write(fs)

batch = sub(batch, "~/femu_fs.sh \"$root\"", "~/femu_fs_c5.sh \"$root\"")
batch = sub(batch, "# Paper C formal runs", "# Paper C C5 runs (generated by exp5/make_c5_scripts.py from exp3/c3_batch.sh)")
open(sys.argv[4], "w", encoding="utf-8", newline="\n").write(batch)
print("written")
