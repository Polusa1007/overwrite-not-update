#!/usr/bin/env python3
"""Paper C, C7: derive the run script, block map and batch runner of C7 from the C1/C3 files, leaving them unchanged.

    make_c7_scripts.py exp/femu_fs.sh exp/fs_map.py exp3/c3_batch.sh femu_fs_c7.sh fs_map_c7.py c7_batch.sh

femu_fs_c7.sh: two tools (dbupd, logapp) from exp7/c7_wl.py, whose existing data are created in /mnt/live right after
the source tree, before any block map; fs_map_c7.py is uploaded instead of fs_map.py. fs_map_c7.py: also maps /mnt/live
(class live, which analyze_c.py already knows). c7_batch.sh calls femu_fs_c7.sh."""
import sys

base, fmap, batch = (open(p, encoding="utf-8", newline="").read().replace("\r\n", "\n") for p in sys.argv[1:4])


def sub(s, a, b):
    assert s.count(a) == 1, a
    return s.replace(a, b)


fs = sub(base, "    dd)     echo 'dd if=/mnt/src.tar of=/mnt/copy.img bs=1M conv=fsync status=none' ;;\n",
         "    dd)     echo 'dd if=/mnt/src.tar of=/mnt/copy.img bs=1M conv=fsync status=none' ;;\n"
         "    dbupd)  echo 'python3 /tmp/c7_wl.py run dbupd /mnt/live' ;;\n"
         "    logapp) echo 'python3 /tmp/c7_wl.py run logapp /mnt/live' ;;\n")
fs = sub(fs, 'G "$MKFS && sudo mount $MOPT /dev/nvme0n1 /mnt && sudo cp -a /usr /mnt/src && sudo sync"\n',
         'G "$MKFS && sudo mount $MOPT /dev/nvme0n1 /mnt && sudo cp -a /usr /mnt/src && sudo sync"\n'
         '# C7: data that the tool will update, created before any block map\n'
         'G "echo $(base64 -w0 ~/c7_wl.py) | base64 -d > /tmp/c7_wl.py"\n'
         'G "sudo python3 /tmp/c7_wl.py prep $TOOL /mnt/live && sudo sync && sudo du -sm /mnt/live" > "$OUT/prep_live.txt" 2>&1\n')
fs = sub(fs, 'G "echo $(base64 -w0 ~/fs_map.py) | base64 -d > /tmp/fs_map.py"\n',
         'G "echo $(base64 -w0 ~/fs_map_c7.py) | base64 -d > /tmp/fs_map.py"\n')
open(sys.argv[4], "w", encoding="utf-8", newline="\n").write(fs)

fmap = sub(fmap, '    tree(os.path.join(mnt, "src"), "src")\n',
           '    tree(os.path.join(mnt, "src"), "src")\n'
           '    if os.path.isdir(os.path.join(mnt, "live")):   # C7: data updated by the tool\n'
           '        tree(os.path.join(mnt, "live"), "live")\n')
open(sys.argv[5], "w", encoding="utf-8", newline="\n").write(fmap)

batch = sub(batch, "~/femu_fs.sh \"$root\"", "~/femu_fs_c7.sh \"$root\"")
batch = sub(batch, "# Paper C formal runs", "# Paper C C7 runs (generated by exp7/make_c7_scripts.py from exp3/c3_batch.sh)")
open(sys.argv[6], "w", encoding="utf-8", newline="\n").write(batch)
print("written")
